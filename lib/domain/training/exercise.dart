enum Equipment {
  bodyweight,
  pullUpBar,
  dumbbells,
  barbell,
  bench,
  cable,
  machine,
  cardioMachine,
}

bool canDo(Exercise exercise, Set<Equipment> have) =>
    exercise.needs.difference({...have, Equipment.bodyweight}).isEmpty;

enum MuscleGroup {
  chest,
  back,
